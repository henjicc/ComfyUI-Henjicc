export function translator(locale) {
    const chinese = /^zh(?:[-_]|$)/i.test(locale ?? "");
    return (message, values = {}) => {
        const text = chinese ? message : (english[message] ?? message);
        return text.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
    };
}

export function responseError(t, message, status) {
    // Raw host errors can contain English/Python details; expose localized known errors only.
    return Object.hasOwn(english, message) ? t(message) : t("请求失败 ({status})", { status });
}
